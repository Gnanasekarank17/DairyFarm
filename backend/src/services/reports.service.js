const PDFDocument = require('pdfkit');
const ExcelJS = require('exceljs');
const config = require('../config');
const logger = require('../config/logger');

const generateInvoicePDF = (invoice, business) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50 });
    const buffers = [];
    doc.on('data', (chunk) => buffers.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(buffers)));
    doc.on('error', reject);

    // Header
    doc.rect(0, 0, doc.page.width, 80).fill('#2563EB');
    doc.fillColor('#FFFFFF').fontSize(22).text(business.name, 50, 20);
    doc.fontSize(10).text(`${business.address} | GST: ${business.gst} | Ph: ${business.phone}`, 50, 50);

    doc.fillColor('#111827').moveDown(3);

    // Invoice Title
    doc.fontSize(16).text('MILK DELIVERY INVOICE', { align: 'center' });
    doc.moveDown(0.5);

    // Invoice details table
    const startY = doc.y;
    const col1 = 50, col2 = 300;
    const rowH = 25;

    const rows = [
      ['Invoice Number', invoice.invoiceNumber],
      ['Customer Name', invoice.customerName],
      ['Month / Year', `${invoice.month} / ${invoice.year}`],
      ['Daily Quantity', `${invoice.dailyQuantity} Liters`],
      ['Rate Per Liter', `₹${invoice.ratePerLiter}`],
      ['Total Days in Month', String(parseInt(invoice.deliveredDays) + parseInt(invoice.missedDays))],
      ['Delivered Days', invoice.deliveredDays],
      ['Missed Days', invoice.missedDays],
      ['Total Quantity', `${invoice.totalQuantity} Liters`],
    ];

    rows.forEach(([label, value], i) => {
      const y = startY + i * rowH;
      if (i % 2 === 0) doc.rect(col1, y - 3, 500, rowH).fill('#F9FAFB');
      doc.fillColor('#374151').fontSize(11).text(label, col1 + 5, y + 5);
      doc.text(value, col2, y + 5);
    });

    // Amount row
    const amountY = startY + rows.length * rowH;
    doc.rect(col1, amountY - 3, 500, rowH + 5).fill('#DCFCE7');
    doc.fillColor('#166534').fontSize(13).text('Amount Due', col1 + 5, amountY + 5);
    doc.text(`₹${invoice.amount}`, col2, amountY + 5);

    // Missed delivery details
    const missedDates = JSON.parse(invoice.missedDetails || '[]');
    if (missedDates.length > 0) {
      doc.fillColor('#111827').moveDown(3);
      doc.fontSize(12).text('Missed Delivery Dates:', col1);
      doc.fontSize(10).fillColor('#6B7280').text(missedDates.join(', '), col1);
    }

    // Footer
    doc.fillColor('#9CA3AF').fontSize(9)
       .text(`Generated by ${business.name} | ${new Date().toLocaleString()}`, 50, doc.page.height - 50, { align: 'center' });

    doc.end();
  });
};

const generateMonthlyReport = async (data) => {
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet('Monthly Report');

  sheet.columns = [
    { header: 'Customer', key: 'name', width: 25 },
    { header: 'Mobile', key: 'mobile', width: 15 },
    { header: 'Milk Type', key: 'milkType', width: 15 },
    { header: 'Daily Qty (L)', key: 'dailyQuantity', width: 15 },
    { header: 'Rate (₹/L)', key: 'ratePerLiter', width: 12 },
    { header: 'Delivered Days', key: 'deliveredDays', width: 16 },
    { header: 'Missed Days', key: 'missedDays', width: 14 },
    { header: 'Total Qty (L)', key: 'totalQuantity', width: 15 },
    { header: 'Amount (₹)', key: 'amount', width: 15 },
    { header: 'Payment Status', key: 'paymentStatus', width: 16 },
  ];

  // Style header
  sheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  sheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF2563EB' } };

  data.forEach((row) => sheet.addRow(row));

  // Totals row
  const total = data.reduce((s, r) => s + parseFloat(r.amount || 0), 0);
  const lastRow = sheet.addRow({ name: 'TOTAL', amount: total });
  lastRow.font = { bold: true };
  lastRow.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFDCFCE7' } };

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
};

module.exports = { generateInvoicePDF, generateMonthlyReport };
